import { activityMonitor } from "../core/activity.js";
import { DEFAULT_MODEL, getApiKey, API_BASE } from "../upstream/gemini-api.js";
import type { ExtractedContent } from "../core/types.js";
import { withTimeout } from "../core/http.js";
import { fetchWithContext, type WebSearchContext } from "../upstream/context.js";
import { readResponseText, ResponseTooLargeError } from "./body.js";

const EXTRACTION_PROMPT = `Extract the complete readable content from this URL as clean markdown. Include the page title, all text content, code blocks, and tables. Do not summarize. URL: `;

function extractHeadingTitle(text: string): string | null {
  const match = text.match(/^#{1,2}\s+(.+)/m);
  if (!match) return null;
  const cleaned = match[1].replace(/\*+/g, "").trim();
  return cleaned || null;
}

export async function extractWithUrlContext(url: string, signal?: AbortSignal, context?: WebSearchContext): Promise<ExtractedContent | null> {
  signal?.throwIfAborted();
  const apiKey = await getApiKey(context, signal);
  signal?.throwIfAborted();
  if (!apiKey) return null;
  const requestSignal = withTimeout(signal, 60_000);
  const activityId = activityMonitor.logStart({ type: "api", query: `url_context: ${url}` });
  try {
    const request = {
      contents: [{ parts: [{ text: EXTRACTION_PROMPT + url }] }],
      tools: [{ url_context: {} }]
    };
    const response = await fetchWithContext(`${API_BASE}/models/${DEFAULT_MODEL}:generateContent`, {
      method: "POST",
      headers: { "Content-Type": "application/json", "x-goog-api-key": apiKey },
      body: JSON.stringify(request),
      signal: requestSignal
    }, context);
    requestSignal.throwIfAborted();
    if (!response.ok) {
      activityMonitor.logComplete(activityId, response.status);
      return null;
    }
    const data = JSON.parse(await readResponseText(response, requestSignal)) as { candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }> };
    activityMonitor.logComplete(activityId, response.status);
    const content = data.candidates?.[0]?.content?.parts?.map((part) => part.text).filter(Boolean).join("\n") ?? "";
    if (!content || content.length < 50) return null;
    const title = extractHeadingTitle(content) ?? new URL(url).hostname;
    return { url, title, content, error: null, extraction: { transport: "gemini", completeness: "unknown", warnings: ["Content generated by Gemini from URL context; verify against the original document"], generated: true } };
  } catch (error) {
    activityMonitor.logComplete(activityId, 0);
    signal?.throwIfAborted();
    if (error instanceof ResponseTooLargeError) throw error;
    return null;
  }
}
